# 設定の略号 -> 環境変数
cfg() {
  case $1 in
    def) echo "" ;;
    a) echo "ENOMOTO_MIP_AGG_INT=1" ;;
    pcr6) echo "ENOMOTO_MIP_PROBE_CLIQUE=1 ENOMOTO_MIP_PROBE_REPRESOLVE=1 ENOMOTO_T_MIP_PROBE_REPRESOLVE_MAX=6" ;;
    g) echo "ENOMOTO_MIP_AGG_INT=1 ENOMOTO_MIP_PROBE_CLIQUE=1 ENOMOTO_MIP_PROBE_REPRESOLVE=1 ENOMOTO_T_MIP_PROBE_REPRESOLVE_MAX=6" ;;
    gd) echo "ENOMOTO_MIP_AGG_INT=1 ENOMOTO_MIP_PROBE_CLIQUE=1 ENOMOTO_MIP_PROBE_REPRESOLVE=1 ENOMOTO_T_MIP_PROBE_REPRESOLVE_MAX=6 ENOMOTO_MIP_DOMCOL=1" ;;
    gi) echo "ENOMOTO_MIP_PRESOLVE_GI=1" ;;
    *) echo "$CFG_EXTRA" ;;
  esac
}
